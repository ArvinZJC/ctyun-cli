// TestCompletionShellPreservesCursorArguments executes generated shell glue
// and checks that the resolver receives separate words only through the cursor.
func TestCompletionShellPreservesCursorArguments(t *testing.T) {
	for _, shell := range []string{"bash", "zsh"} {
		path, err := exec.LookPath(shell)
		if err != nil {
			t.Logf("%s unavailable: shell execution checks skipped", shell)
			continue
		}
		for _, test := range []struct {
			name, words, want string
			cursor            int
		}{
			{"empty final word", "ctyun plugin list ''", "__complete\nplugin\nlist\n\n", 3},
			{"earlier word", "ctyun plugin li --available", "__complete\nplugin\nli\n", 2},
			{"quoted word", "ctyun --profile 'two words' plugin li", "__complete\n--profile\ntwo words\nplugin\nli\n", 4},
		} {
			t.Run(shell+"/"+test.name, func(t *testing.T) {
				var generated bytes.Buffer
				if err := runCompletion(&generated, []string{shell}); err != nil {
					t.Fatal(err)
				}
				capture := filepath.Join(t.TempDir(), "arguments")
				setup := "ctyun() { printf '%s\\n' \"$@\" > \"$CTYUN_COMPLETION_CAPTURE\"; }; compadd() { :; };\n"
				var script string
				if shell == "bash" {
					script = setup + generated.String() + "\nCOMP_WORDS=(" + test.words + "); COMP_CWORD=" + strconv.Itoa(test.cursor) + "; _ctyun_completion\n"
				} else {
					script = setup + "words=(" + test.words + "); CURRENT=" + strconv.Itoa(test.cursor+1) + ";\n" + generated.String()
				}
				command := exec.Command(path, "-c", script)
				command.Env = append(os.Environ(), "CTYUN_COMPLETION_CAPTURE="+capture)
				if output, err := command.CombinedOutput(); err != nil {
					t.Fatalf("execute completion: %v\n%s", err, output)
				}
				got, err := os.ReadFile(capture)
				if err != nil {
					t.Fatal(err)
				}
				if string(got) != test.want {
					t.Fatalf("resolver arguments = %q, want %q", got, test.want)
				}
			})
		}
	}
}

// TestPowerShellCompletionBoundsASTArguments guards cursor and quoted-value
// handling where PowerShell is unavailable to execute the generated completer.
func TestPowerShellCompletionBoundsASTArguments(t *testing.T) {
	var generated bytes.Buffer
	if err := runCompletion(&generated, []string{"powershell"}); err != nil {
		t.Fatal(err)
	}
	for _, required := range []string{
		"$element.Extent.EndOffset -ge $cursorPosition",
		"$element.Value",
		"$arguments += $wordToComplete",
		"PSNativeCommandArgumentPassing",
		"$process.Dispose()",
	} {
		if !strings.Contains(generated.String(), required) {
			t.Errorf("PowerShell completer is missing cursor/argument guard %q", required)
		}
	}
}

// TestPowerShellNativeCompletion records the exact argv delivered by the registered native completer.
func TestPowerShellNativeCompletion(t *testing.T) {
	for _, shell := range []string{"powershell", "pwsh"} {
		t.Run(shell, func(t *testing.T) {
			interpreter, err := exec.LookPath(shell)
			if err != nil {
				t.Skip("PowerShell interpreter unavailable")
			}
			dir := t.TempDir()
			binary := filepath.Join(dir, "ctyun")
			if runtime.GOOS == "windows" {
				binary += ".exe"
			}
			source := filepath.Join(dir, "capture.go")
			mustWrite(t, source, `package main

import (
	"encoding/json"
	"fmt"
	"os"
)

func main() {
	data, err := json.Marshal(os.Args[1:])
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(os.Getenv("CTYUN_COMPLETION_CAPTURE"), data, 0600); err != nil {
		panic(err)
	}
	fmt.Println("--lang")
}`)
			if data, err := exec.Command("go", "build", "-o", binary, source).CombinedOutput(); err != nil {
				t.Fatalf("build native argument recorder: %v\n%s", err, data)
			}
			var generated bytes.Buffer
			if err := runCompletion(&generated, []string{"powershell"}); err != nil {
				t.Fatal(err)
			}
			script := filepath.Join(dir, "test-completion.ps1")
			// Windows PowerShell 5.1 needs a UTF-8 BOM for the non-ASCII test inputs.
			mustWrite(t, script, "\ufeff"+generated.String()+`
$ErrorActionPreference = 'Stop'
$modes = @('Legacy')
if (Get-Variable PSNativeCommandArgumentPassing -ErrorAction SilentlyContinue) {
  $modes += 'Standard', 'Windows'
}
foreach ($mode in $modes) {
  if ($modes.Count -gt 1) { $PSNativeCommandArgumentPassing = $mode }
  foreach ($value in @('', '   ', 'two words', '"', 'a"b', 'a""b', 'a\"b', 'a\\"b', 'path\', 'space path\\', '云端路径', '--flag')) {
    foreach ($cursor in @('', '--la')) {
      $line = "ctyun --profile '$value' version $cursor"
      $result = [System.Management.Automation.CommandCompletion]::CompleteInput($line, $line.Length, $null)
      $expected = @('__complete', '--profile', $value, 'version', $cursor)
      $actual = Get-Content -Raw -Encoding UTF8 -LiteralPath $env:CTYUN_COMPLETION_CAPTURE | ConvertFrom-Json
      if ($actual.Count -ne $expected.Count -or '--lang' -notin @($result.CompletionMatches.CompletionText)) {
        throw "Mode $mode, input '$line': argv $($actual -join ' | '), candidates $($result.CompletionMatches.CompletionText)"
      }
      for ($i = 0; $i -lt $expected.Count; $i++) {
        if (-not [string]::Equals($expected[$i], $actual[$i], [StringComparison]::Ordinal)) {
          throw "Mode $mode, input '$line': expected argument '$($expected[$i])', received '$($actual[$i])'"
        }
      }
    }
  }
}`)
			cmd := exec.Command(interpreter, "-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-File", script)
			cmd.Dir = dir
			cmd.Env = append(os.Environ(), "PATH="+dir+string(os.PathListSeparator)+os.Getenv("PATH"), "CTYUN_COMPLETION_CAPTURE="+filepath.Join(dir, "arguments.json"))
			if data, err := cmd.CombinedOutput(); err != nil {
				t.Fatalf("native completion: %v\n%s", err, data)
			}
		})
	}
}

// TestBashInlineCompletionReplacesOnlyReadlineFragment verifies the candidate
// Bash inserts when Readline keeps the option name and equals sign on the line.
func TestBashInlineCompletionReplacesOnlyReadlineFragment(t *testing.T) {
	bash, err := exec.LookPath("bash")
	if err != nil {
		t.Skip("Bash unavailable")
	}
	var generated bytes.Buffer
	if err := runCompletion(&generated, []string{"bash"}); err != nil {
		t.Fatal(err)
	}
	for _, tc := range []struct {
		words, fragment, want string
	}{
		{"--output=j", "j", "json"},
		{"--output=", "", "json"},
		{"--output=j", "--output=j", "--output=json"},
		{"--output = j", "j", "json"},
		{"--output =", "", "json"},
	} {
		inline := strings.ReplaceAll(tc.words, " ", "")
		script := generated.String() + `
ctyun() {
  [[ $# == 4 && $1 == __complete && $2 == plugin && $3 == list && $4 == "$EXPECTED_INLINE" ]] || return 1
  printf '%s\n' '--output=json'
}
COMP_WORDS=(ctyun plugin list ` + tc.words + `)
COMP_CWORD=$((${#COMP_WORDS[@]} - 1))
COMP_LINE="ctyun plugin list $EXPECTED_INLINE"
_ctyun_completion ctyun "$FRAGMENT" list
printf '%s' "${COMPREPLY[0]}"`
		cmd := exec.Command(bash, "-c", script)
		cmd.Env = append(os.Environ(), "EXPECTED_INLINE="+inline, "FRAGMENT="+tc.fragment)
		got, err := cmd.CombinedOutput()
		if err != nil || string(got) != tc.want {
			t.Errorf("words %q, fragment %q: got %q, want %q (%v)", tc.words, tc.fragment, got, tc.want, err)
		}
	}
}
